//! `build.rs` support for the per-app AOT crates of m5_pocket_app.
//!
//! [`emit`] places the exported host profile in `OUT_DIR/pocket_profile.rs`
//! (`pocket_profile_build`, from `POCKETJS_PROFILE_RS`) and writes
//! `OUT_DIR/m5_fonts.rs`: a `load_fonts_in_place(ui)` that loads the font
//! atlases the generated `include.rs` names through
//! `m5_pocket_aot::load_font_in_place`, so their coverage stays in flash
//! instead of the heap copies the generated `load_fonts` makes.
use std::{env, fs, path::PathBuf};

pub fn emit() {
    pocket_profile_build::emit(pocket_profile_build::Export::Required);
    println!("cargo:rerun-if-env-changed=POCKETJS_AOT_DIR");
    let aot = PathBuf::from(env::var_os("POCKETJS_AOT_DIR").expect(
        "POCKETJS_AOT_DIR is unset: build this crate through m5_pocket_app() (idf.py with CONFIG_M5_POCKET_APP_MODE_AOT)",
    ));
    let include = aot.join("include.rs");
    println!("cargo:rerun-if-changed={}", include.display());
    let text = fs::read_to_string(&include)
        .unwrap_or_else(|error| panic!("{}: {error}", include.display()));
    // The generated loader: `fn load_fonts(ui: &mut microts::Ui) {` followed
    // by one `load_font_atlas(include_bytes!("<file>"))` line per atlas.
    let body = text
        .split_once("fn load_fonts(")
        .map(|(_, rest)| rest.split_once("\n}").map_or(rest, |(body, _)| body))
        .unwrap_or("");
    let mut out = String::from(
        "// Generated by m5_pocket_aot_build from include.rs; do not edit.\n\
         #[allow(dead_code)]\n\
         fn load_fonts_in_place(ui: &mut microts::Ui) {\n",
    );
    for line in body.lines() {
        let Some((_, rest)) = line.split_once("include_bytes!(\"") else {
            continue;
        };
        let Some((file, _)) = rest.split_once('"') else {
            continue;
        };
        out.push_str(&format!(
            "    assert!(m5_pocket_aot::load_font_in_place(ui, include_bytes!(concat!(env!(\"POCKETJS_AOT_DIR\"), \"/{file}\"))));\n"
        ));
    }
    out.push_str("}\n");
    let target = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("m5_fonts.rs");
    fs::write(target, out).expect("write m5_fonts.rs");
}
