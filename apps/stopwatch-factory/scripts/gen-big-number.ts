// Writes ../BigNumber.tsx: the big-number watch face shows one RGBA4444 tile
// per (palette, position, digit), produced by import-factory-assets.ts. Image
// sources must be static in the MicroTS view subset, so every tile has its own
// <Show>. Run from the repository root after the asset import:
//
//   bun apps/stopwatch-factory/scripts/gen-big-number.ts

import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

// Tile top-left corners: factory digit centres (233 ± 42, 233 ± 51) minus (64, 66).
const corners = [
  [127, 116],
  [211, 116],
  [127, 218],
  [211, 218],
];
const digitsPerPosition = [3, 10, 6, 10];
const lines: string[] = [];
for (let position = 0; position < 4; position++) {
  const [left, top] = corners[position];
  // Each digit turns about its own centre and moves with the face rotation
  // (anchors 7..10 of the root model).
  lines.push(
    `      <View class="absolute left-[${left}] top-[${top}] w-[128] h-[128]" ` +
      `style={{ translateX: props.dx[${7 + position}] ?? 0, translateY: props.dy[${7 + position}] ?? 0, rotate: props.rotation }}>`,
  );
  for (let palette = 0; palette < 4; palette++) {
    for (let digit = 0; digit < digitsPerPosition[position]; digit++) {
      lines.push(
        `      <Show when={props.palette === ${palette} && props.d${position} === ${digit}}>` +
          `<Image class="absolute left-0 top-0 w-[128] h-[128]" src="images/bn_${palette}${position}_${digit}.png" /></Show>`,
      );
    }
  }
  lines.push("      </View>");
}
const source = `// Generated by scripts/gen-big-number.ts; do not edit.
import { Show } from "solid-js";
import { Image, View } from "@pocketjs/framework/solid/components";
import type { Deg, i32 } from "@pocketjs/framework/solid/std";

// Factory big_number face: four recoloured digit images, hours above minutes.
export default function BigNumber(props: {
  palette: i32;
  d0: i32;
  d1: i32;
  d2: i32;
  d3: i32;
  dx: i32[];
  dy: i32[];
  rotation: Deg;
}) {
  return (
    <View class="absolute left-0 top-0 w-[466] h-[466]">
${lines.join("\n")}
    </View>
  );
}
`;
writeFileSync(join(resolve(import.meta.dir, ".."), "BigNumber.tsx"), source);
