//! [`emit_images`]: the application's pictures read in place from flash.
//!
//! MicroTS bakes each image the generated `load_images` registers as an IMG
//! pak entry, `images/image-<n>.img`: the `@<density>x` variant at the host's
//! raster density, in the format and sampling `images.json` declares, with
//! the size check of the guest build. The generated loader uploads each entry
//! with `upload_img_entry`, which copies the pixels into the heap.
use std::{env, fs, path::PathBuf};

/// Bytes before an IMG entry's pixels (`parse_img_header` in pocketjs-core).
const IMG_HEADER_BYTES: usize = 8;

/// One image the generated `load_images` registers: its name and its IMG
/// entry, relative to the AOT directory.
struct Generated {
    name: String,
    entry: String,
}

/// The `upload_img_entry(include_bytes!("<entry>"))` and
/// `register_image("<name>", id)` pairs of the generated `include.rs`.
fn generated_images(include: &str) -> Vec<Generated> {
    let mut images = Vec::new();
    for line in include
        .lines()
        .filter(|line| line.contains("upload_img_entry("))
    {
        let entry = line
            .split_once("include_bytes!(\"")
            .and_then(|(_, rest)| rest.split_once('"'))
            .map(|(entry, _)| entry);
        let name = line
            .split_once("register_image(\"")
            .and_then(|(_, rest)| rest.split_once('"'))
            .map(|(name, _)| name);
        if let (Some(name), Some(entry)) = (name, entry) {
            images.push(Generated {
                name: name.to_string(),
                entry: entry.to_string(),
            });
        }
    }
    images
}

/// Write `OUT_DIR/m5_images.rs` with
///
/// - `fn load_images_in_place(ui: &mut microts::Ui)`, which registers every
///   image the generated `include.rs` registers, under the same names, through
///   `m5_pocket_aot::load_image_in_place`: each texture reads its IMG entry
///   from flash and is decoded into the heap when a frame draws it, bounded by
///   `set_texture_budget`;
/// - `const M5_IMAGE_BYTES: usize`, the pixel bytes of all of them.
///
/// A generated image line in a form this parser does not know fails the
/// build, so a change of the generated loader is not skipped. Call after
/// [`crate::emit`].
pub fn emit_images() {
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let aot = PathBuf::from(env::var_os("POCKETJS_AOT_DIR").expect("POCKETJS_AOT_DIR"));
    let include = aot.join("include.rs");
    println!("cargo:rerun-if-changed={}", include.display());
    let text = fs::read_to_string(&include)
        .unwrap_or_else(|error| panic!("{}: {error}", include.display()));
    let images = generated_images(&text);
    let registered = text.matches("register_image(").count();
    assert_eq!(
        images.len(),
        registered,
        "{}: {registered} images registered, {} read as upload_img_entry lines",
        include.display(),
        images.len()
    );
    let mut total = 0usize;
    let mut code = String::from(
        "// Generated by m5_pocket_aot_build::emit_images; do not edit.\n\
         /// The application's pictures, read in place from their IMG entries.\n\
         #[allow(dead_code)]\n\
         fn load_images_in_place(ui: &mut microts::Ui) {\n",
    );
    for image in &images {
        let path = aot.join(&image.entry);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = fs::metadata(&path)
            .unwrap_or_else(|error| panic!("{}: {error}", path.display()))
            .len() as usize;
        assert!(bytes > IMG_HEADER_BYTES, "{}: no pixels", path.display());
        total += bytes - IMG_HEADER_BYTES;
        code.push_str(&format!(
            "    m5_pocket_aot::load_image_in_place(ui, {:?}, include_bytes!(concat!(env!(\"POCKETJS_AOT_DIR\"), \"/{}\")));\n",
            image.name, image.entry
        ));
    }
    code.push_str("}\n");
    code.push_str(&format!(
        "/// Pixel bytes of the pictures load_images_in_place registers.\n\
         #[allow(dead_code)]\n\
         const M5_IMAGE_BYTES: usize = {total};\n"
    ));
    fs::write(out.join("m5_images.rs"), code).expect("write m5_images.rs");
}
