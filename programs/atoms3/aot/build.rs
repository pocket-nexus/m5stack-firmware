//! Fonts in place (m5_pocket_aot_build) and the factory artwork as RGB565
//! textures read from flash.
//!
//! The generated `load_images` uploads each image's RGBA8888 pixels to the
//! heap: 18 artworks x 64 KiB would exceed the AtomS3's internal RAM. This
//! script converts every image the generated `include.rs` names to RGB565
//! (PSM_5650, the pak encoder's B5:G6:R5 little-endian layout) into OUT_DIR
//! and writes `load_images_in_place`, which registers them with
//! `upload_texture_from`: a texture is decoded into the heap when it is
//! drawn and released again under the core's texture budget.
use std::{env, fs, path::PathBuf};

fn main() {
    m5_pocket_aot_build::emit();
    let aot = PathBuf::from(env::var_os("POCKETJS_AOT_DIR").expect("POCKETJS_AOT_DIR"));
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let include = fs::read_to_string(aot.join("include.rs")).expect("include.rs");
    let body = include
        .split_once("fn load_images(")
        .map(|(_, rest)| rest.split_once("\n}").map_or(rest, |(body, _)| body))
        .unwrap_or("");
    let mut code = String::from(
        "// Generated by build.rs from include.rs; do not edit.\n\
         #[allow(dead_code)]\n\
         fn load_images_in_place(ui: &mut microts::Ui) {\n",
    );
    for (index, line) in body.lines().enumerate() {
        // { let id = ui.core_mut().upload_texture(include_bytes!("images/image-0.rgba"), 128, 128, ...PSM_8888); ...; ui.register_image("img/a.png", id); }
        let Some((_, rest)) = line.split_once("include_bytes!(\"") else {
            continue;
        };
        let (file, rest) = rest.split_once('"').expect("image file");
        let mut numbers = rest.trim_start_matches(')').split(',').skip(1);
        let width: usize = numbers.next().expect("width").trim().parse().expect("width");
        let height: usize = numbers.next().expect("height").trim().parse().expect("height");
        let name = line
            .split_once("register_image(\"")
            .and_then(|(_, rest)| rest.split_once('"'))
            .map(|(name, _)| name)
            .expect("image name");
        let source = aot.join(file);
        println!("cargo:rerun-if-changed={}", source.display());
        let rgba = fs::read(&source).expect("image pixels");
        assert_eq!(rgba.len(), width * height * 4, "{}", source.display());
        let mut rgb565 = Vec::with_capacity(width * height * 2);
        for pixel in rgba.chunks_exact(4) {
            let (r, g, b) = (pixel[0] as u16 >> 3, pixel[1] as u16 >> 2, pixel[2] as u16 >> 3);
            rgb565.extend_from_slice(&((b << 11) | (g << 5) | r).to_le_bytes());
        }
        let target = format!("image-{index}.rgb565");
        fs::write(out.join(&target), rgb565).expect("write image");
        code.push_str(&format!(
            "    {{\n        static PIXELS: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{target}\"));\n        \
             let storage: alloc::rc::Rc<dyn AsRef<[u8]>> = alloc::rc::Rc::new(PIXELS);\n        \
             let id = ui.core_mut().upload_texture_from(storage, 0..PIXELS.len(), {width}, {height}, \
             microts::pocketjs_core::spec::psm::PSM_5650, 0);\n        \
             assert!(id >= 0);\n        ui.register_image(\"{name}\", id);\n    }}\n"
        ));
    }
    code.push_str("}\n");
    fs::write(out.join("m5_images.rs"), code).expect("write m5_images.rs");
}
